import { act, fireEvent, render, screen } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { BlitzScreen } from "./BlitzScreen";
const api = vi.hoisted(() => ({ fetchGameQuestions: vi.fn(), record: vi.fn() }));
vi.mock("next/navigation", () => ({ useRouter: () => ({ push: vi.fn() }), useSearchParams: () => new URLSearchParams("tempo=relaxed") }));
vi.mock("../api/games", () => ({ fetchGameQuestions: api.fetchGameQuestions }));
vi.mock("../hooks/useGameStats", () => ({ useGameStats: () => ({ record: api.record }) }));
vi.mock("../components/GameShell", () => ({ GameShell: ({ children }: { children: React.ReactNode }) => <div>{children}</div> }));
vi.mock("../components/GameStage", () => ({ GameStage: ({ children }: { children: React.ReactNode }) => <div>{children}</div> }));
vi.mock("../components/GameSummary", () => ({ GameSummary: ({ titles }: { titles: { title: string }[] }) => <div>Знахідки: {titles.map(item => item.title).join(", ")}</div> }));
vi.mock("../../../shared/ui/CoverImage", () => ({ CoverImage: () => null }));
vi.mock("../../../shared/ui/MovieInfoButton", () => ({ MovieInfoButton: () => <button>Опис</button> }));
afterEach(() => vi.useRealTimers());
it("keeps relaxed questions open and advances only when the player chooses Next", async () => {
  const card = { tmdbId: 1, mediaType: "movie", title: "Answer", backdropUrl: "/frame.jpg" };
  api.fetchGameQuestions.mockResolvedValue([{ id: "q1", prompt: "Що це за фільм?", card, options: [card, { ...card, tmdbId: 2, title: "Decoy" }], answerId: 1 }]);
  render(<BlitzScreen />);
  const answer = await screen.findByRole("button", { name: "Answer" });
  vi.useFakeTimers();
  act(() => { vi.advanceTimersByTime(15_000); });
  expect(answer).toBeEnabled();
  fireEvent.click(answer);
  act(() => { vi.advanceTimersByTime(5_000); });
  expect(screen.getByRole("button", { name: "Підсумок" })).toBeInTheDocument();
  expect(api.record).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole("button", { name: "Підсумок" }));
  expect(screen.getByText("Знахідки: Answer, Answer, Decoy")).toBeInTheDocument();
  expect(api.record).toHaveBeenCalledWith({ score: 1 });
});
